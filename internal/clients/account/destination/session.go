package destination

import (
	"context"
	"strings"

	"github.com/pkg/errors"
	"golang.org/x/oauth2"
	"golang.org/x/oauth2/clientcredentials"

	destclient "github.com/sap/crossplane-provider-btp/internal/openapi_clients/btp-destination-service-api-go/pkg"
)

const errFetchToken = "cannot fetch destination service access token"

// Session holds the OAuth2 token source of one Destination service binding.
// Build one per Connect and derive the clients and the binding check from it,
// so they share one token request.
type Session struct {
	ts  oauth2.TokenSource
	uri string
}

// NewSession creates a Session authenticating via OAuth2 client credentials.
func NewSession(cred DestinationCredential) *Session {
	ts := (&clientcredentials.Config{
		ClientID:     cred.ClientID,
		ClientSecret: cred.ClientSecret,
		TokenURL:     cred.TokenURL,
	}).TokenSource(context.Background())
	return &Session{ts: ts, uri: cred.URI}
}

func (s *Session) apiClient() *destclient.APIClient {
	cfg := destclient.NewConfiguration()
	cfg.HTTPClient = oauth2.NewClient(context.Background(), s.ts)
	cfg.Servers = destclient.ServerConfigurations{
		{URL: strings.TrimRight(s.uri, "/") + "/destination-configuration"},
	}
	return destclient.NewAPIClient(cfg)
}

// DestinationClient returns a client for subaccount-level destinations.
func (s *Session) DestinationClient() DestinationClientI {
	return &destinationClient{api: s.apiClient().DestinationsOnSubaccountLevelAPI}
}

// CertificateClient returns a client for uploaded subaccount-level certificates.
func (s *Session) CertificateClient() CertificateClientI {
	return &certificateClient{api: s.apiClient().CertificatesOnSubaccountLevelAPI}
}

// GeneratedCertificateClient returns a client for certificates generated by
// the Destination service.
func (s *Session) GeneratedCertificateClient() GeneratedCertificateClientI {
	return &certificateClient{api: s.apiClient().CertificatesOnSubaccountLevelAPI}
}

// TokenSubaccount returns the ext_attr.subaccountid claim of the binding's
// access token, or "" when the claim is absent or the token is not a
// decodable JWT. An error means the token could not be fetched.
func (s *Session) TokenSubaccount() (string, error) {
	tok, err := s.ts.Token()
	if err != nil {
		return "", errors.Wrap(err, errFetchToken)
	}
	return subaccountFromJWT(tok.AccessToken), nil
}
